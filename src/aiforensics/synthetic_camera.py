"""Controlled P1-G02 synthetic camera and labeled line families."""
from __future__ import annotations
import numpy as np
from scipy.spatial.transform import Rotation


def camera_ground_truth(image_shape=(720, 1280), focal=900., principal=None, angles_deg=(35., 30., 40.)):
    h, w = image_shape
    cx, cy = (w/2., h/2.) if principal is None else principal
    K = np.array([[focal, 0., cx], [0., focal, cy], [0., 0., 1.]])
    R = Rotation.from_euler('xyz', angles_deg, degrees=True).as_matrix()
    coords = (K @ R).T
    vps = coords[:, :2] / coords[:, 2:3]
    return K, R, vps


def labeled_segments_from_vps(vps: np.ndarray, image_shape=(720, 1280),
                               count_per_group=45, endpoint_noise=0.35, seed=43):
    """Build three groups of finite image line segments with known VPs.

    This is a controlled 2D projective-geometry fixture, not an actual image
    generated by the 3D rendering equation. All segment endpoints are in-frame.
    """
    rng = np.random.default_rng(seed)
    h, w = image_shape
    groups = []
    for vp in np.asarray(vps):
        group = []
        for _ in range(count_per_group):
            for _attempt in range(100):
                mid = np.array([rng.uniform(0.16*w, 0.84*w), rng.uniform(0.16*h, 0.84*h)])
                delta = vp - mid
                if np.linalg.norm(delta) > 100:
                    break
            direction = delta / np.linalg.norm(delta)
            length = rng.uniform(45, 145)
            endpoints = np.r_[mid - 0.5*length*direction, mid + 0.5*length*direction]
            endpoints += rng.normal(0, endpoint_noise, 4)
            group.append(endpoints)
        groups.append(np.array(group))
    return groups
