def _catalog() -> dict[str, ModuleForm]:
    labels={**MODULES,'P8-E01':'Individual conditional evidence',
            'P8-E02':'Dependency-aware familywise hypotheses',
            'P8-E03':'Explainable offline evidence report'}
    if set(labels)!=set(COMMANDS):
        raise WorkflowError('module registry and CLI allowlist mismatch')
    return {mid:ModuleForm(
        mid, labels[mid], COMMANDS[mid], 'image' if mid in IMAGE_ONLY else 'json',
        _REQUIRED.get(mid,()), _PROVENANCE[mid.split('-')[0]],
        'Sadece sentetik demo örneğidir; gerçek fizik kanıtı değildir.' if mid in _EXAMPLES
        else 'Görüntü girdisi ve bağımsız doğrulama koşulları ayrı ele alınır.',
        _EXAMPLES.get(mid),_RECOMMENDED_BEFORE.get(mid,()))
        for mid in labels}


