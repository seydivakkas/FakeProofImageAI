def load_synthetic_example(module_id: str, *, root:Path|None=None,
                           destination:Path|None=None) -> tuple[Path,dict]:
    """Copies a reproducible sample WITHOUT overwriting or authenticating data.

    P7-S02 includes relative .npz dependencies, so its demo must generate those
    independent synthetic frame stacks alongside the JSON in destination.
    """
    if module_id not in FORM_CATALOG or module_id in IMAGE_ONLY:
        raise WorkflowError('Yalnız JSON kullanan kayıtlı modüller desteklenir')
    if destination is None:
        raise WorkflowError('Örnek için açık bir çıktı dizini gerekli')
    destination=Path(destination).resolve()
    destination.mkdir(parents=True,exist_ok=True)
    if module_id=='P7-S02':
        from .sensor_fingerprint_synthetic import write_synthetic_fingerprint_fixture
        file,_=write_synthetic_fingerprint_fixture(destination)
        return file,json.loads(file.read_text(encoding='utf-8'))
    root=Path(root or _package_root())
    try:
        src=_source_example(root,module_id)
        raw=src.read_bytes()
    except WorkflowError:
        # Distribution wheels omit generated outputs; reconstruct controlled
        # sample via the versioned physics fixture generator when available.
        import importlib
        generator=_SYNTHETIC_GENERATORS.get(module_id)
        if generator is None:raise
        module_name,func_name=generator
        result=getattr(importlib.import_module('.'+module_name, __package__),func_name)()
        sample=result[0] if isinstance(result,tuple) else result
        raw=json.dumps(sample,ensure_ascii=False,allow_nan=False,indent=2).encode('utf-8')
    if len(raw)>MAX_MANIFEST_SIZE:
        raise WorkflowError('Örnek JSON boyut sınırını aşıyor')
    data=json.loads(raw)
    if not isinstance(data,dict):
        raise WorkflowError('Örnek manifest bir nesne olmalı')
    path=destination/(module_id.replace('-','_')+'_SYNTHETIC.json')
    if path.exists():
        raise WorkflowError('Örnek zaten var; mevcut ölçümleri korumak için üzerine yazılmadı')
    path.write_bytes(raw)
    return path,data


def load_form_data(module_id:str,path:str|Path)->dict:
    if module_id not in FORM_CATALOG or module_id in IMAGE_ONLY:
        raise WorkflowError('Seçilen modül JSON manifesti kullanmıyor')
    path=Path(path)
    if path.suffix.lower()!='.json' or not path.is_file() or path.stat().st_size>MAX_MANIFEST_SIZE:
        raise WorkflowError('Geçerli, 32 MB altı JSON dosyası seçilmeli')
    def reject_nan(x):
        raise WorkflowError('JSON sonlu olmayan sayı içeriyor: '+x)
    value=json.loads(path.read_text(encoding='utf-8'),parse_constant=reject_nan)
    if not isinstance(value,dict):
        raise WorkflowError('Manifest kökü bir JSON nesnesi olmalı')
    return value


def structural_checks(module_id:str,data:Mapping[str,Any])->list[str]:
    if module_id not in FORM_CATALOG:
        raise WorkflowError('Kayıtsız modül')
    if not isinstance(data,Mapping):
        return ['Manifest kökü nesne olmalıdır']
    keys=FORM_CATALOG[module_id].required_fields
    missing=[key for key in keys if key not in data or data[key] is None]
    reasons=['Eksik üst alan: '+key for key in missing]
    # Validate only under E01's existing contract; E02 and E03 re-evaluate E01
    # and require lineage/fusion fields. This is not an assertion of camera truth.
    if module_id.startswith('P8-'):
        if data.get('schema_version')!='p8.e01.v1':
            reasons.append('P8 E01 giriş şeması p8.e01.v1 olmalı')
        if not isinstance(data.get('records'),list) or not data['records']:
            reasons.append('Boş/eksik kanıt kayıt dizisi')
    return reasons


def _leaf_type(value):
    if value is None:return 'null'
    if type(value) is bool:return 'boolean'
    if type(value) is int:return 'integer'
    if type(value) is float:return 'number'
    if isinstance(value,str):return 'string'
    if isinstance(value,list):return 'array'
    if isinstance(value,dict):return 'object'
    raise WorkflowError('JSON dışı alan tipi')


def list_form_fields(value:Mapping[str,Any],*,limit=MAX_LEAF_FIELDS):
    """One widget per scalar; containers are expandable as typed JSON snippets."""
    if not isinstance(value,Mapping):raise WorkflowError('Form JSON nesnesi olmalı')
    rows=[]
    def rec(v,path,depth):
        if len(rows)>=limit:return
        kind=_leaf_type(v)
        if kind in ('array','object'):
            rows.append({'path':tuple(path),'kind':kind,'value':
                         f'{len(v)} öğe (JSON düzenleyici)'})
            if depth<3:
                if isinstance(v,dict):
                    for k,child in list(v.items())[:100]:rec(child,path+[k],depth+1)
                else:
                    for i,child in enumerate(v[:15]):rec(child,path+[i],depth+1)
        else:
            rows.append({'path':tuple(path),'kind':kind,'value':str(v) if v is not None else 'null'})
    for key,child in value.items():rec(child,[key],1)
    return rows


def field_path_label(path:Sequence[str|int])->str:
    return '.'.join(str(x) if isinstance(x,str) else f'[{x}]' for x in path)


def _decode_value(text:str,old_value):
    kind=_leaf_type(old_value)
    if kind=='string':return text
    try:decoded=json.loads(text,parse_constant=lambda name:(_ for _ in ()).throw(ValueError(name)))
    except (ValueError,json.JSONDecodeError) as exc:raise WorkflowError('Alan için geçerli JSON değeri gerekli') from exc
    if _leaf_type(decoded)!=kind and not (kind=='number' and type(decoded) in (int,float)):
        raise WorkflowError(f'{kind} tipinde alan bekleniyor')
    return decoded


def update_form_field(value:Mapping[str,Any],path:Sequence[str|int],text:str)->dict:
    """Transactional copy; incorrect edits never mutate the live form."""
    if not path:raise WorkflowError('Alan yolu boş olamaz')
    data=copy.deepcopy(value)
    node=data
    try:
        for key in path[:-1]:node=node[key]
        old=node[path[-1]]
    except (KeyError,IndexError,TypeError) as exc:raise WorkflowError('Alan yolu geçersiz') from exc
    node[path[-1]]=_decode_value(text,old)
    if len(json.dumps(data,ensure_ascii=False,allow_nan=False).encode('utf-8'))>MAX_MANIFEST_SIZE:
        raise WorkflowError('Form boyutu aşıldı')
    return data


def save_form_data(module_id:str,data:dict,path:str|Path)->Path:
    if module_id not in FORM_CATALOG or module_id in IMAGE_ONLY:
        raise WorkflowError('JSON formu gereken bir modül seçin')
    if structural_checks(module_id,data):
        raise WorkflowError('Üst alanlar eksik: '+'; '.join(structural_checks(module_id,data)))
    destination=Path(path).expanduser().resolve()
    destination.parent.mkdir(parents=True,exist_ok=True)
    content=json.dumps(data,ensure_ascii=False,indent=2,allow_nan=False).encode('utf-8')
    if len(content)>MAX_MANIFEST_SIZE:raise WorkflowError('JSON boyutu aşıldı')
    fd,tmp=tempfile.mkstemp(dir=destination.parent,prefix='.form-',suffix='.tmp')
    try:
        with os.fdopen(fd,'wb') as target:target.write(content)
        os.replace(tmp,destination)
    finally:
        if os.path.exists(tmp):os.unlink(tmp)
    return destination


@dataclass(frozen=True)
class PlanStep:
    module_id:str
    command:str
    input_path:str|None
    state:str
    reasons:tuple[str,...]
    previous_selected:tuple[str,...]
    sha256:str|None

    def as_dict(self):
        return dict(module_id=self.module_id,command=self.command,
                    input_path=self.input_path,state=self.state,reasons=list(self.reasons),
                    previous_selected=list(self.previous_selected),input_sha256=self.sha256)


def _input_preflight(mid:str,path:str|Path|None)->tuple[str|None,list[str],str|None]:
    errors=[]
    if path is None or not str(path).strip():return None,['Girdi seçilmedi'],None
    p=Path(path).expanduser()
    if not p.is_file():return str(p),['Girdi dosyası bulunamadı'],None
    kind=FORM_CATALOG[mid].input_kind
    if kind=='image':
        if p.suffix.lower() not in IMAGE_EXTENSIONS:errors.append('Görüntü uzantısı uygun değil')
        if p.stat().st_size>200*1024*1024:errors.append('Görüntü >200 MB')
    else:
        try:
            obj=load_form_data(mid,p)
            errors.extend(structural_checks(mid,obj))
        except (WorkflowError,OSError,ValueError) as exc:errors.append(str(exc))
        # A PRNU manifest may cite relative npz references; never assume they
        # exist merely because the JSON parses.
        if not errors and mid=='P7-S02':
            for entry in [obj.get('reference_npz'),*[x.get('npz') for x in obj.get('queries',[]) if isinstance(x,dict)]]:
                if not isinstance(entry,str) or not entry or Path(entry).is_absolute() or '..' in Path(entry).parts or not (p.parent/entry).is_file():
                    errors.append('RAW NPZ referansı eksik/güvensiz: '+str(entry))
    h=None
    if not errors:
        with p.open('rb') as stream:
            dig=hashlib.sha256()
            for block in iter(lambda:stream.read(1<<20),b''):dig.update(block)
        h=dig.hexdigest()
    return str(p.resolve()),errors,h


def build_execution_plan(selected:Sequence[str],inputs:Mapping[str,str|Path],*,
                         preferred:Mapping[str,Sequence[str]]|None=None)->dict:
    """Deterministic topological order. Dependencies never manufacture inputs.

    Physical modules are generally independently parameterized: a G02 result
    isn't an automatic calibration for P5 or P6. Preferred predecessors only
    establish run *order when both are explicitly selected*.
    """
    if not isinstance(selected,(list,tuple)) or len(selected)!=len(set(selected)):
        raise WorkflowError('Seçilen modüller yinelenmemeli')
    if any(m not in FORM_CATALOG for m in selected):raise WorkflowError('Bilinmeyen modül')
    if not selected:raise WorkflowError('En az bir modül seçilmeli')
    spec=preferred if preferred is not None else _RECOMMENDED_BEFORE
    choices=set(selected)
    deps={m:tuple(d for d in spec.get(m,()) if d in choices) for m in selected}
    # Deterministic stable order uses input ordering to resolve ties.
    ordered=[]
    pending=set(selected)
    while pending:
        ready=[m for m in selected if m in pending and set(deps[m])<=set(ordered)]
        if not ready:raise WorkflowError('Bağımlılık döngüsü: '+', '.join(sorted(pending)))
        item=ready[0];ordered.append(item);pending.remove(item)
    steps=[]
    for mid in ordered:
        path,problems,digest=_input_preflight(mid,inputs.get(mid))
        steps.append(PlanStep(mid,FORM_CATALOG[mid].command,path,
                              'BLOCKED' if problems else 'READY',tuple(problems),deps[mid],digest))
    return {'schema':'fakeproof.execution_plan.v1',
            'created_utc':datetime.now(timezone.utc).isoformat(),
            'decision':'NO_AI_ORIGIN_CONCLUSION',
            'scientific_validation':'NOT_PERFORMED',
            'automatic_upstream_data_reuse':False,
            'ready_count':sum(s.state=='READY' for s in steps),
            'blocked_count':sum(s.state=='BLOCKED' for s in steps),
            'steps':[s.as_dict() for s in steps]}


def execute_plan(project,plan:dict,*,halt_on_failure=True,stop_requested=None,on_step=None)->dict:
    """Uses Project.run's shell=False CLI; never calls a physics model on guesses."""
    if plan.get('schema')!='fakeproof.execution_plan.v1':raise WorkflowError('Plan şeması farklı')
    events=[]
    states={}
    for step in plan['steps']:
        mid=step['module_id']
        if stop_requested is not None and stop_requested():
            events.append({'module_id':mid,'state':'CANCELLED_BEFORE_START'});break
        if step['state']!='READY':
            entry={'module_id':mid,'state':'BLOCKED','reasons':step['reasons']}
            events.append(entry);states[mid]='BLOCKED'
            if on_step:on_step(entry)
            continue
        blocked_by=[p for p in step['previous_selected'] if states.get(p)!='SUCCEEDED']
        if blocked_by:
            entry={'module_id':mid,'state':'BLOCKED_DEPENDENCY','reasons':blocked_by}
            events.append(entry);states[mid]='BLOCKED_DEPENDENCY'
            if on_step:on_step(entry)
            continue
        inp=Path(step['input_path'])
        if not inp.is_file() or hashlib.sha256(inp.read_bytes()).hexdigest()!=step['input_sha256']:
            entry={'module_id':mid,'state':'INPUT_CHANGED','reasons':['SHA-256 uyuşmazlığı']}
            events.append(entry);states[mid]='INPUT_CHANGED'
            if on_step:on_step(entry)
            if halt_on_failure:break
            continue
        try:
            run,folder=project.run(mid,str(inp))
            state=run['state']
            entry={'module_id':mid,'state':state,'run_id':run['run_id'],'output_dir':str(folder)}
        except Exception as exc:
            state='ERROR';entry={'module_id':mid,'state':state,'reasons':[str(exc)]}
        states[mid]=state;events.append(entry)
        if on_step:on_step(entry)
        if halt_on_failure and state!='SUCCEEDED':break
    return {'schema':'fakeproof.execution_result.v1','plan':plan,
            'events':events,'decision':'NO_AI_ORIGIN_CONCLUSION',
            'real_camera_acceptance':'NOT_PERFORMED'}
