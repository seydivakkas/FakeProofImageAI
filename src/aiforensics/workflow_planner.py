def _package_root() -> Path:
    return Path(__file__).resolve().parents[2]


def _source_example(root: Path, module_id: str) -> Path:
    spec=FORM_CATALOG[module_id]
    if not spec.example_path:
        raise WorkflowError('Bu modül için görüntü seçin')
    path=(root/spec.example_path).resolve()
    if not path.is_file():
        packaged=Path(__file__).resolve().parent/'demo_forms'/(module_id.replace('-','_')+'.json')
        if packaged.is_file():return packaged
        raise WorkflowError('Örnek dosya bulunamadı; kendi ölçüm manifestinizi yükleyin: '+spec.example_path)
    return path


